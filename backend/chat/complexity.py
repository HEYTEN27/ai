"""
Авто-размышления: включать ли «размышления» Qwen3 для этого вопроса.

Размышления делают ответы на задачи заметно точнее (модель сначала решает «на черновике»),
но стоят времени: сотни-тысячи лишних токенов ≈ 10–30 секунд на RTX 2060 Super.
Для «привет» или «переведи слово» это пустая трата, а для задачи по алгоритмам — выгодно.

Решаем простыми правилами без запроса к модели (лишний запрос сам по себе стоил бы секунды):
каждый признак сложности добавляет баллы, от 2 баллов — думаем. Сюда не попадают просьбы
написать большой текст или игру: им размышления съели бы место под сам ответ в 8K контекста.
"""

import re

THRESHOLD = 2

SIGNS = [
    # (баллы, регулярное выражение, что означает)
    (2, r"уравнени|интеграл|производн|предел\w* функц|вероятност|матриц|определител|докаж|теорем|"
        r"реши (задач|пример|систем)|вычисли|сколько (будет|способов|вариантов)|комбинатор|логарифм", "математика"),
    (2, r"найди (ошибку|баг)|почему (не работает|падает|выдаёт|выдает|ошибка)|исправь (код|ошибку|баг)|"
        r"оптимизир|сложност\w* алгоритм|o\(n|асимптотик|рекурси|динамическ\w+ программ|утечк\w+ памяти", "отладка, алгоритмы"),
    (2, r"головоломк|логическ\w+ задач|загадк|парадокс", "логика"),
    (1, r"сравни|проанализируй|разбери|спланируй|по шагам|пошагово|обоснуй|аргумент|плюсы и минусы|что лучше", "анализ"),
    (1, r"\d+\s*[\+\-\*/\^×÷]\s*\d+|\d+\s*%|\bx\s*[=²^]", "вычисления"),
    (1, r"```|Traceback|Error:|exception|undefined is not|TypeError|SyntaxError", "код или ошибка"),
]
# Длинный текст ответа — размышления только отнимут место у самого ответа
OUTPUT_HEAVY = re.compile(
    r"(сделай|создай|напиши|сгенерируй|нарисуй)\s+(\S+\s+)?(игр|страниц|сайт|презентаци|документ|реферат|доклад|"
    r"эссе|сочинени|письм|таблиц|схем|стих|рассказ)", re.IGNORECASE)


def assess(question: str) -> tuple[bool, list[str]]:
    """(думать ли, какие признаки сложности нашлись)."""
    text = question or ""
    if len(text.strip()) < 12:
        return False, []
    score, reasons = 0, []
    for points, pattern, label in SIGNS:
        if re.search(pattern, text, re.IGNORECASE):
            score += points
            reasons.append(label)
    if text.count("?") >= 3:
        score += 1
        reasons.append("несколько вопросов")
    if len(text) > 600:
        score += 1
        reasons.append("длинное условие")
    if OUTPUT_HEAVY.search(text) and "отладка, алгоритмы" not in reasons:
        score -= 2
    return score >= THRESHOLD, reasons
