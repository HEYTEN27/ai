"""
Стили ответов (этап 15а) — как в Claude: выбираются у поля ввода для каждого чата.

Стиль — короткая приписка к системному промпту. Персона задаёт «кто отвечает»
(учитель, программист), а стиль — «как подробно и каким тоном» в этом конкретном чате.
"""

STYLES = {
    "normal": ("Обычный", ""),
    "concise": ("Кратко", "Стиль ответа в этом чате: КРАТКО — 2–5 предложений или короткий список, без вступлений, "
                          "повторов и «воды»; подробности — только если попросят."),
    "detailed": ("Подробно", "Стиль ответа в этом чате: ПОДРОБНО — объясняй по шагам, с примерами, разбирай нюансы "
                             "и типичные ошибки, в конце — краткий итог."),
    "simple": ("Простыми словами", "Стиль ответа в этом чате: ПРОСТЫМИ СЛОВАМИ — как новичку, без жаргона, с бытовыми "
                                   "аналогиями; каждый термин поясняй."),
    "formal": ("Официально", "Стиль ответа в этом чате: ОФИЦИАЛЬНО-ДЕЛОВОЙ — вежливо и нейтрально, без шуток и эмодзи, "
                             "чёткая структура, грамотный язык."),
}


def hint(style: str | None) -> str:
    return STYLES.get(style or "normal", STYLES["normal"])[1]
